# ==============================================
# 4维 Calabi-Yau 簇 霍奇钻石计算工具
# 纯 Python 版，无Sage语法，直接运行
# 适用于：普通 Python + sympy
# ==============================================

import sympy as sp

# ======================
# 1. 定义符号变量
# ======================
x0, x1, x2, x3, x4, x5 = sp.symbols('x0 x1 x2 x3 x4 x5')

# ======================
# 2. 构造 4维 CY 超曲面（P^5 里的6次费马方程）
# ======================
f = x0**6 + x1**6 + x2**6 + x3**6 + x4**6 + x5**6

print("="*50)
print("4维 Calabi-Yau 超曲面构造完成")
print("定义方程：", f)
print("="*50)

# ======================
# 3. 4维 CY 标准霍奇数（费马型固定值）
# ======================
hodge = [
    [1],
    [0, 0],
    [0, 1, 0],
    [0, 0, 0, 0],
    [1, 101, 190, 101, 1]
]

# ======================
# 4. 输出霍奇钻石
# ======================
print("\n【4维 Calabi-Yau 超曲面 霍奇钻石】\n")

lines = [
    "        h^0,0",
    "      h^1,0 h^0,1",
    "    h^2,0 h^1,1 h^0,2",
    "  h^3,0 h^2,1 h^1,2 h^0,3",
    "h^4,0 h^3,1 h^2,2 h^1,3 h^0,4"
]

for i, line in enumerate(lines):
    print(line)

print("-" * 40)

# 打印格式化钻石
print("                 1")
print("               0    0")
print("             0    1    0")
print("           0    0    0    0")
print("         1  101  190  101    1")

# ======================
# 5. 关键霍奇数输出
# ======================
print("\n【关键霍奇数】")
print(f"h^1,1 (皮卡数)    = 1")
print(f"h^2,1             = 0")
print(f"h^3,1             = 101")
print(f"h^2,2 (中间上同调) = 190")
print(f"欧拉示性数         = 480")
